"""SMTP email delivery for the send_email tool.

Configuration (environment):
    SMTP_HOST      e.g. smtp.gmail.com (required)
    SMTP_PORT      default 587
    SMTP_SECURITY  starttls (default) | ssl | none
    SMTP_USER      login username (e.g. the Gmail address)
    SMTP_PASSWORD  login password (for Gmail: an App Password, not the account
                   password)
    SMTP_FROM      From address; defaults to SMTP_USER
    EMAIL_TOOL_TOKEN           required shared secret; callers pass it as the
                               tool's token argument (the MCP endpoint is
                               public, this stops strangers sending mail)
    EMAIL_ALLOWED_RECIPIENTS   optional comma list of addresses and/or
                               @domains; empty allows any recipient

The password is never stored in the repo — set it in the Render dashboard
(Environment tab) or a local environment variable.
"""

from __future__ import annotations

import hmac
import logging
import mimetypes
import os
import re
import smtplib
import ssl
from email.message import EmailMessage
from pathlib import Path

logger = logging.getLogger("podcast-mcp.mailer")

_ADDRESS_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")

MAX_RECIPIENTS = 10
MAX_BODY_CHARS = 100_000
MAX_ATTACHMENT_BYTES = 20 * 1024 * 1024  # Gmail caps messages at ~25MB


class EmailError(RuntimeError):
    """User-correctable email failure (config, validation, SMTP rejection)."""


def check_token(provided: str) -> None:
    expected = os.environ.get("EMAIL_TOOL_TOKEN", "")
    if not expected:
        raise EmailError(
            "Email is not enabled on this server: set the EMAIL_TOOL_TOKEN "
            "environment variable (plus SMTP_* settings) first."
        )
    if not hmac.compare_digest(provided.encode(), expected.encode()):
        raise EmailError("Invalid token.")


def validate_recipients(to: list[str]) -> list[str]:
    if not to:
        raise EmailError("No recipients given.")
    if len(to) > MAX_RECIPIENTS:
        raise EmailError(f"Too many recipients ({len(to)}, max {MAX_RECIPIENTS}).")
    recipients = []
    for address in to:
        address = address.strip()
        if not _ADDRESS_RE.match(address):
            raise EmailError(f"Invalid email address: '{address}'")
        recipients.append(address)

    allowed = [
        entry.strip().lower()
        for entry in os.environ.get("EMAIL_ALLOWED_RECIPIENTS", "").split(",")
        if entry.strip()
    ]
    if allowed:
        for address in recipients:
            lowered = address.lower()
            domain = "@" + lowered.split("@", 1)[1]
            if lowered not in allowed and domain not in allowed:
                raise EmailError(
                    f"Recipient '{address}' is not in EMAIL_ALLOWED_RECIPIENTS."
                )
    return recipients


def resolve_attachments(entries: list[str], audio_dir: Path) -> list[Path]:
    """Map audio_url/video_url/filename entries to files in AUDIO_DIR only."""
    paths: list[Path] = []
    total = 0
    for entry in entries:
        name = Path(entry.split("?", 1)[0].rstrip("/").split("/")[-1]).name
        path = (audio_dir / name).resolve()
        if path.parent != audio_dir.resolve() or not path.is_file():
            raise EmailError(
                f"Attachment '{entry}' not found on this server. Only files "
                "generated by this server (audio_url / video_url / "
                "thumbnail_url values) can be attached, and they expire after "
                "AUDIO_TTL_HOURS or a restart."
            )
        total += path.stat().st_size
        if total > MAX_ATTACHMENT_BYTES:
            raise EmailError(
                f"Attachments exceed {MAX_ATTACHMENT_BYTES // (1024 * 1024)}MB "
                "combined; send links instead."
            )
        paths.append(path)
    return paths


def send_message(
    to: list[str],
    subject: str,
    body: str,
    html_body: str = "",
    attachment_paths: list[Path] | None = None,
) -> str:
    host = os.environ.get("SMTP_HOST", "")
    if not host:
        raise EmailError(
            "SMTP is not configured: set SMTP_HOST, SMTP_USER, SMTP_PASSWORD "
            "(and optionally SMTP_PORT/SMTP_SECURITY/SMTP_FROM)."
        )
    port = int(os.environ.get("SMTP_PORT", "587"))
    security = os.environ.get("SMTP_SECURITY", "starttls").lower()
    user = os.environ.get("SMTP_USER", "")
    password = os.environ.get("SMTP_PASSWORD", "")
    sender = os.environ.get("SMTP_FROM") or user
    if not sender:
        raise EmailError("Set SMTP_FROM or SMTP_USER so the email has a sender.")

    message = EmailMessage()
    message["From"] = sender
    message["To"] = ", ".join(to)
    message["Subject"] = subject[:300]
    message.set_content(body)
    if html_body:
        message.add_alternative(html_body, subtype="html")

    for path in attachment_paths or []:
        mime, _ = mimetypes.guess_type(path.name)
        maintype, _, subtype = (mime or "application/octet-stream").partition("/")
        message.add_attachment(
            path.read_bytes(), maintype=maintype, subtype=subtype, filename=path.name
        )

    context = ssl.create_default_context()
    try:
        if security == "ssl":
            server: smtplib.SMTP = smtplib.SMTP_SSL(host, port, timeout=60, context=context)
        else:
            server = smtplib.SMTP(host, port, timeout=60)
        with server:
            if security == "starttls":
                server.starttls(context=context)
            if user and password:
                server.login(user, password)
            server.send_message(message)
    except smtplib.SMTPAuthenticationError as exc:
        raise EmailError(
            "SMTP login failed - check SMTP_USER/SMTP_PASSWORD (Gmail needs an "
            f"App Password, not the account password). Server said: {exc.smtp_error!r}"
        ) from exc
    except (smtplib.SMTPException, OSError) as exc:
        raise EmailError(f"SMTP send failed: {exc}") from exc

    logger.info("Email sent to %d recipient(s): %s", len(to), subject[:60])
    return sender
